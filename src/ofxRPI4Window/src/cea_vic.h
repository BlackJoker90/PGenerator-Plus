static inline int cea_vrefresh(uint32_t clock, const uint16_t *h, const uint16_t *v, uint32_t flags)
{
	if (h[3] == 0 || v[3] == 0)
		return 0;
	uint64_t num = clock, den = (uint64_t)h[3] * v[3];
	if (flags & DRM_MODE_FLAG_INTERLACE)
		num *= 2;
	if (flags & DRM_MODE_FLAG_DBLSCAN)
		den *= 2;
	if (v[4] > 1)
		den *= v[4];
	return (int)((num * 1000 + den / 2) / den);
}

/* 59.94 Hz and friends share a VIC with the integer rate */
static inline uint32_t cea_alternate_clock(const struct cea_vic_timing *t)
{
	if (cea_vrefresh(t->clock, t->h, t->v, t->flags) % 6 != 0)
		return t->clock;
	if (t->v[0] == 480 || t->v[0] == 240)
		return (uint32_t)(((uint64_t)t->clock * 1001 + 500) / 1000);
	return (uint32_t)(((uint64_t)t->clock * 1000 + 500) / 1001);
}

/* VIC of a mode as the kernel derives it, 0 for none. Aspect ratio is not
   compared: without DRM_CLIENT_CAP_ASPECT_RATIO the mode we set has none. */
static inline int cea_vic_for_mode(const drmModeModeInfo *m)
{
	const uint32_t ignore = (0x1fU << 14) | (0xfU << 19); /* 3D, picture aspect */
	if (m->clock == 0)
		return 0;
	uint32_t picos = 1000000000U / m->clock;
	for (unsigned i = 0; i < sizeof(cea_vic_timings) / sizeof(cea_vic_timings[0]); i++) {
		struct cea_vic_timing t = cea_vic_timings[i];
		uint32_t clock2 = cea_alternate_clock(&t);
		if (picos != 1000000000U / t.clock && picos != 1000000000U / clock2)
			continue;
		for (;;) {
			if (m->hdisplay == t.h[0] && m->hsync_start == t.h[1] && m->hsync_end == t.h[2] &&
			    m->htotal == t.h[3] && m->hskew == t.h[4] &&
			    m->vdisplay == t.v[0] && m->vsync_start == t.v[1] && m->vsync_end == t.v[2] &&
			    m->vtotal == t.v[3] && m->vscan == t.v[4] &&
			    (m->flags & ~ignore) == (t.flags & ~ignore))
				return t.vic;
			/* the kernel's cea_mode_alternate_timings(): 240p/288p with
			   one more line */
			bool alt = (((t.vic == 8 || t.vic == 9 || t.vic == 12 || t.vic == 13) && t.v[3] <= 262) ||
			            ((t.vic == 23 || t.vic == 24 || t.vic == 27 || t.vic == 28) && t.v[3] <= 313));
			if (!alt)
				break;
			t.v[1]++; t.v[2]++; t.v[3]++;
		}
	}
	return 0;
}

/* drm_default_rgb_quant_range(): 1 Limited, 2 Full */
static inline int cea_default_rgb_quant_range(const drmModeModeInfo *m)
{
	return cea_vic_for_mode(m) > 1 ? 1 : 2;
}
